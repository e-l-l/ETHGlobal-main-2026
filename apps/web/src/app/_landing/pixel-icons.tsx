export type PixelIconName = keyof typeof ICONS;

export function PixelIcon({
  name,
  size = 24,
  accent = "fill-leaf",
  className,
  label,
}: {
  name: PixelIconName;
  size?: number;
  /** Fill class for the "+" pixels. */
  accent?: string;
  className?: string;
  label?: string;
}) {
  const rows = ICONS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      className={cn("shrink-0 [shape-rendering:crispEdges]", className)}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      {rows.flatMap((row, y) =>
        [...row].map((ch, x) =>
          ch === "." ? null : <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" className={ch === "+" ? accent : "fill-current"} />,
        ),
      )}
    </svg>
  );
}

/** Icon on a square tile: the standard way icons sit in cards. */
export function IconTile({ name, tone = "light", size = 44 }: { name: PixelIconName; tone?: "light" | "dark" | "lime"; size?: number }) {
  const t = {
    light: { box: "bg-well text-hunter", accent: "fill-leaf" },
    dark: { box: "bg-deep text-honeydew", accent: "fill-lime" },
    lime: { box: "bg-lime text-hunter", accent: "fill-forest" },
  }[tone];
  return (
    <span aria-hidden className={cn("grid shrink-0 place-items-center rounded-md", t.box)} style={{ width: size, height: size }}>
      <PixelIcon name={name} size={Math.round(size * 0.55)} accent={t.accent} />
    </span>
  );
}
