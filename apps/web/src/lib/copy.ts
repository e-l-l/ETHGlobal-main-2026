/** Brand panel eyebrow for an onboarding step, e.g. "Step 1 of 4 · Prove your business". */
export function stepEyebrow(lang: Lang, at: number) {
  const c = copy[lang];
  return `${c.steps(at)} · ${c.stepNames[at - 1] ?? ""}`;
}
