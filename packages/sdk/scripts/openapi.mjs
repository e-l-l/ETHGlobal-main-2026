#!/usr/bin/env node
// Regenerate src/api/openapi.gen.ts from a RUNNING agents API:
//
//   node scripts/openapi.mjs [apiUrl]        default $MRA_API_URL or http://localhost:8000
//
// Fetches {apiUrl}/openapi.json and writes one TS type per components.schemas entry plus a route list.
// No dependencies. The hand-checked src/api/types.ts stays authoritative (several agents_api.py routes
// return untyped dicts, which OpenAPI shows as `unknown`); diff the two after regenerating:
//
//   git diff --no-index src/api/types.ts src/api/openapi.gen.ts   (or just read the route list)
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const apiUrl = (process.argv[2] ?? process.env.MRA_API_URL ?? "http://localhost:8000").replace(/\/+$/, "");
const out = join(dirname(fileURLToPath(import.meta.url)), "../src/api/openapi.gen.ts");

let spec;
try {
  const res = await fetch(`${apiUrl}/openapi.json`, { signal: AbortSignal.timeout(10_000) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  spec = await res.json();
} catch (e) {
  console.error(`could not fetch ${apiUrl}/openapi.json (${e.message}). Start the API: cd agents && uv run uvicorn mra_agents.api:app`);
  process.exit(1);
}

const ident = (s) => s.replace(/[^A-Za-z0-9_]/g, "_");
const refName = (ref) => ident(ref.split("/").pop());

function ts(schema, indent = "") {
  if (!schema || Object.keys(schema).length === 0) return "unknown";
  if (schema.$ref) return refName(schema.$ref);
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map((s) => ts(s, indent)).join(" | ");
  if (schema.allOf) return schema.allOf.map((s) => ts(s, indent)).join(" & ");
  const type = Array.isArray(schema.type) ? schema.type : [schema.type];
  const parts = type.map((t) => {
    switch (t) {
      case "string":
        return "string";
      case "integer":
        return "number | bigint";
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        if (schema.prefixItems) return `[${schema.prefixItems.map((s) => ts(s, indent)).join(", ")}]`;
        return `Array<${ts(schema.items ?? {}, indent)}>`;
      case "object": {
        const props = schema.properties ?? {};
        const req = new Set(schema.required ?? []);
        const lines = Object.entries(props).map(([k, v]) => `${indent}  ${JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${ts(v, indent + "  ")};`);
        if (schema.additionalProperties && schema.additionalProperties !== false) {
          lines.push(`${indent}  [k: string]: ${schema.additionalProperties === true ? "unknown" : ts(schema.additionalProperties, indent + "  ")};`);
        }
        return lines.length ? `{\n${lines.join("\n")}\n${indent}}` : "Record<string, unknown>";
      }
      default:
        return "unknown";
    }
  });
  return parts.join(" | ");
}

const lines = [
  `// GENERATED by scripts/openapi.mjs from ${apiUrl}/openapi.json (${spec.info?.title ?? "API"} ${spec.info?.version ?? ""}).`,
  "// Do not edit. The hand-checked types in ./types.ts are what the SDK uses.",
  "/* eslint-disable */",
  "",
];
for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
  lines.push(`export type ${ident(name)} = ${ts(schema)};`, "");
}
const routes = [];
for (const [path, ops] of Object.entries(spec.paths ?? {})) {
  for (const [method, op] of Object.entries(ops)) {
    const body = op.requestBody?.content?.["application/json"]?.schema;
    const ok = Object.entries(op.responses ?? {}).find(([code]) => code.startsWith("2"));
    const resp = ok?.[1]?.content?.["application/json"]?.schema;
    routes.push({ method: method.toUpperCase(), path, body: body ? ts(body) : null, response: resp ? ts(resp) : null });
  }
}
lines.push(`export const ROUTES = ${JSON.stringify(routes.map(({ method, path }) => `${method} ${path}`), null, 2)} as const;`, "");
lines.push("export type RouteTypes = {");
for (const r of routes) lines.push(`  ${JSON.stringify(`${r.method} ${r.path}`)}: { body: ${r.body ?? "never"}; response: ${r.response ?? "unknown"} };`);
lines.push("};", "");
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}: ${Object.keys(spec.components?.schemas ?? {}).length} schemas, ${routes.length} routes`);
