#!/usr/bin/env node
// Copy the live contract addresses and ABIs from the backend repo into src/, and regenerate the typed
// `as const` TypeScript modules viem needs for inference.
//
//   node scripts/sync-backend.mjs [path/to/agents]      default: ../../agents (monorepo), then $MRA_AGENTS_DIR
//
// The JSON copies are the reviewed source; the .ts files are generated from them. Re-run after a redeploy.
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const candidates = [process.argv[2], process.env.MRA_AGENTS_DIR, resolve(pkg, "../../agents")].filter(Boolean);
const agents = candidates.find((p) => existsSync(join(p, "deployments")));

const ABIS = {
  AdvanceBook: "advanceBookAbi",
  BusinessPassRegistry: "businessPassRegistryAbi",
  TrancheVault: "trancheVaultAbi",
  RiskHook: "riskHookAbi",
  MockUSDC: "erc20Abi",
};
const DEPLOYMENTS = ["sepolia", "local"];

if (agents) {
  for (const name of Object.keys(ABIS)) copyFileSync(join(agents, "abi", `${name}.json`), join(pkg, "src/abi", `${name}.json`));
  for (const name of DEPLOYMENTS) {
    const src = join(agents, "deployments", `${name}.json`);
    if (existsSync(src)) copyFileSync(src, join(pkg, "src/deployments", `${name}.json`));
  }
  console.log(`copied from ${agents}`);
} else {
  console.log("backend not found; regenerating .ts from the committed JSON only");
}

const header = "// GENERATED by scripts/sync-backend.mjs from the JSON next to this file. Do not edit.\n";
const abiLines = [header];
for (const [name, exportName] of Object.entries(ABIS)) {
  const raw = JSON.parse(readFileSync(join(pkg, "src/abi", `${name}.json`), "utf8"));
  const abi = (Array.isArray(raw) ? raw : raw.abi).filter((x) => x.type === "function" || x.type === "event" || x.type === "error");
  abiLines.push(`/** ${name} (agents/abi/${name}.json) */\nexport const ${exportName} = ${JSON.stringify(abi)} as const;\n`);
}
writeFileSync(join(pkg, "src/abi/index.ts"), abiLines.join("\n"));

const depLines = [header, 'import type { Deployment } from "../chain/deployments.js";\n'];
for (const name of DEPLOYMENTS) {
  const file = join(pkg, "src/deployments", `${name}.json`);
  if (!existsSync(file)) continue;
  const json = JSON.parse(readFileSync(file, "utf8"));
  depLines.push(`/** agents/deployments/${name}.json */\nexport const ${name} = ${JSON.stringify(json, null, 2)} as const satisfies Deployment;\n`);
}
writeFileSync(join(pkg, "src/deployments/index.ts"), depLines.join("\n"));
console.log("wrote src/abi/index.ts and src/deployments/index.ts");
