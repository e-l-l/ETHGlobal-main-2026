"""Regenerate circuits/business_pass/{Prover,Mandate}.toml, the inputs of the Foundry real-proof fixtures.

    uv run python scripts/bizpass_fixtures.py && ../circuits/business_pass/build.sh

Prover.toml  -> drawFirst:       recipient 0xbEEF, offerId 1, minBand 1
Mandate.toml -> registerMandate: MANDATE_FIXTURE below (tier 0, band 1); context = mandateHash % P
Both: one Business Pass at leaf index 0 (secret 123456789, AR=32, revenue band 2, ageOk 1), secret_next 987654321.
"""

from eth_utils import keccak

from mra_agents import zk
from mra_agents.bizpass import CIRCUIT_DIR, Limits, MandateRequest, mandate_context, prover_inputs

SECRET, SECRET_NEXT = 123456789, 987654321
LEAF = zk.business_leaf(SECRET, 32, 2, 1)
MANDATE_FIXTURE = MandateRequest(
    shop_id=keccak(text="chai-stall"),
    agent_key="0x3805Ecc0043365A3d1c6b68ABD41dEC19C988d08",  # vm.addr(0xA6E7)
    recipient="0x000000000000000000000000000000000000bEEF",
    limits=Limits(max_per_draw=100_000_000, max_per_period=250_000_000, period=30 * 86400, expiry=1_800_000_000),
    tier=0, band=1)

HEADER = ("# Fixture: one Business Pass at leaf index 0 of an otherwise empty tree (BusinessPassRegistry.issue),\n"
          "# secret 123456789, AR (32), revenue band 2, ageOk 1. Generated by agents/scripts/bizpass_fixtures.py.\n")


def main() -> None:
    common = dict(secret=SECRET, country=32, revenue_band=2, age_ok=1, leaves=[LEAF], leaf_index=0,
                  secret_next=SECRET_NEXT, min_band=1)
    draw = prover_inputs(**common, context=zk.offer_context("0x000000000000000000000000000000000000bEEF",
                                                            (1).to_bytes(32, "big")))
    (CIRCUIT_DIR / "Prover.toml").write_text(
        HEADER + "# Draw: drawFirst, minBand 1, recipient 0xbEEF, offerId 1, countries [AR, NG, KE, 0].\n" + draw.toml)
    mandate = prover_inputs(**common, context=mandate_context(MANDATE_FIXTURE))
    (CIRCUIT_DIR / "Mandate.toml").write_text(
        HEADER + "# Mandate: registerMandate tier 0 band 1 for MANDATE_FIXTURE (see the script).\n" + mandate.toml)
    print(f"leaf      0x{LEAF:064x}\nroot      0x{draw.root:064x}\nnullifier 0x{draw.nullifier:064x}\n"
          f"next      0x{draw.commitment_next:064x}\nctx draw  0x{draw.context:064x}\nctx mand  0x{mandate.context:064x}")


if __name__ == "__main__":
    main()
